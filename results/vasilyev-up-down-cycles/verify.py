def main():
    c = CYCLE
    l = len(c)
    require(all(isinstance(x, int) and x >= 2 for x in c), "vertices >= 2")
    require(len(set(c)) == l, "vertices distinct (simple cycle)")
    require(all(U(x) != D(x) for x in c), "U and D never coincide on the cycle")
    ups = 0
    downs = 0
    prod = Fraction(1)
    for i in range(l):
        x, y = c[i], c[(i + 1) % l]
        require(y == U(x) or y == D(x), "edge %d -> %d is a step of G" % (x, y))
        if y == U(x):
            ups += 1
            prod *= Fraction(2 * y, 3 * x)
        else:
            downs += 1
            prod *= Fraction(2 * y, x)
    a = ups
    require(ups + downs == l, "step count")
    require((l, a) == (382, 240), "l = 382, a = 240")
    require(prod == Fraction(2 ** l, 3 ** a), "product identity 2^l / 3^a")
    require(3 ** a < 2 ** l, "3^a < 2^l holds")
    require(3 ** (a + 1) < 2 ** l, "3^(a+1) < 2^l: Question 7.1 answered NO")
    require(2 ** l < 3 ** (a + 2), "a = floor(l log_3 2) - 1")
    S = {c[i] for i in range(l) if c[(i + 1) % l] == U(c[i])}
    x = c[0]
    visited = []
    for _ in range(l):
        visited.append(x)
        x = U(x) if x in S else D(x)
    require(visited == c and x == c[0], "primitive orbit of c[0] under T_S")
    ratio = 2 ** l / 3 ** a
    print("l = %d, a = %d, 2^l / 3^a = %.6f > 3, max element = %d" % (l, a, ratio, max(c)))
    print("ALL CHECKS PASSED")


if __name__ == "__main__":
    main()
